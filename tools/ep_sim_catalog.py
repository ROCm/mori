"""Build the EP simulation catalog (MORI_EP_SIM_CATALOG) from the EP tuning configs.

Every tuning rule written by bench_dispatch_combine.py carries the latency it measured;
this collects them into one latency-vs-tokens curve per (GPU, kernel, EP size, phase,
dtype, hidden_dim, topk, combine quant, zero copy).

    python3 tools/ep_sim_catalog.py > python/mori/ops/ep_sim_catalog.yaml
"""
import argparse
import glob
import json
import os
import sys

# bench_dispatch_combine.py defaults, for rules that do not record them.
BENCH_TOPK = 8
BENCH_NUM_EXPERTS = 256
GPU_PER_NODE = 8

HEADER = """\
# MORI EP simulation catalog: measured dispatch/combine latency per token count.
# Generated by tools/ep_sim_catalog.py from python/mori/ops/tuning_configs; do not edit by
# hand, regenerate. Read at run time from MORI_EP_SIM_CATALOG (comma-separated, later files
# replace equal curves; defaults to this file); MORI_EP_SIM_GPU picks the GPU.
#
# Each curve was measured by tests/python/ops/bench_dispatch_combine.py with every rank
# sending `tokens` tokens routed uniformly at random to `topk` distinct experts out of
# `num_experts`; latency_us is the per-op mean. The simulator reads a call's latency at the
# token count that puts the same load on the busiest rank.
"""


def curves_from(path, root):
    with open(path) as f:
        cfg = json.load(f)
    phase = cfg["phase"]
    grouped = {}
    for rule in cfg["rules"]:
        lat = rule.get("avg_latency_us", rule.get("latency_us"))
        if lat is None or lat <= 0:
            continue
        explicit_topk = "topk" in rule
        key = (
            rule["dtype"],
            int(rule["hidden_dim"]),
            int(rule.get("topk", BENCH_TOPK)),
            (rule.get("quant_type") or "none") if phase == "combine" else "none",
            bool(rule.get("zero_copy", False)) if phase == "combine" else False,
        )
        points = grouped.setdefault(key, {})
        tok = int(rule["num_tokens"])
        # A rule that names its topk beats one that left it to the bench default.
        if tok not in points or explicit_topk:
            points[tok] = float(lat)
    for (dtype, hidden, topk, quant, zero_copy), points in sorted(grouped.items()):
        toks = sorted(points)
        entry = {
            "gpu": cfg["gpu_model"],
            "kernel": cfg["kernel_type"],
            "ep_size": int(cfg["ep_size"]),
            "gpu_per_node": GPU_PER_NODE,
            "phase": phase,
            "dtype": dtype,
            "hidden_dim": hidden,
            "topk": topk,
            "num_experts": BENCH_NUM_EXPERTS,
        }
        if phase == "combine":
            entry["quant"] = quant
            entry["zero_copy"] = "true" if zero_copy else "false"
        entry["tokens"] = ",".join(str(t) for t in toks)
        entry["latency_us"] = ",".join(f"{points[t]:g}" for t in toks)
        entry["measured"] = '"' + os.path.relpath(path, root) + '"'
        yield entry


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    default_dir = os.path.join(here, "..", "python", "mori", "ops", "tuning_configs")
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--tuning-dir", default=default_dir)
    args = ap.parse_args()
    root = os.path.dirname(os.path.abspath(args.tuning_dir))

    out = [HEADER]
    for path in sorted(glob.glob(os.path.join(args.tuning_dir, "*.json"))):
        for entry in curves_from(path, root):
            lines = [
                f"- {k}: {v}" if i == 0 else f"  {k}: {v}"
                for i, (k, v) in enumerate(entry.items())
            ]
            out.append("\n".join(lines) + "\n")
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
